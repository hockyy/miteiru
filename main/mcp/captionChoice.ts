import {CAPTION_CODE, listYoutubeCaptionTracks} from "../helpers/youtubeCaptions";
import {pickDefaultSubtitleTracks} from "../../renderer/utils/mediaUtils";

export interface CaptionTrack {
  code: string;
  name: string;
  kind: "uploader" | "automatic";
}

/**
 * The caption tracks Miteiru's subtitle picker offers for a video, from yt-dlp's `-J` output. A track
 * whose code the caption download refuses is left out, so no tool offers what can't be opened.
 */
export const describeTracks = (info: any): CaptionTrack[] => (
  listYoutubeCaptionTracks(info).filter((track) => CAPTION_CODE.test(track.code)).map((track) => ({
    code: track.code,
    name: track.name,
    kind: track.isAutoGenerated ? "automatic" : "uploader"
  }))
);

/**
 * The tracks the subtitle picker preselects for a learning language: the best match as the main
 * subtitle and the first English one as the translation. Tracks come in the order
 * `describeTracks` gives them (uploader first), so an uploader track wins a tie.
 */
export const chooseCaptions = (
  tracks: CaptionTrack[],
  languageCode: string
): {main: CaptionTrack | null; translation: CaptionTrack | null} => {
  const picked = pickDefaultSubtitleTracks(
    tracks.map((track, index) => ({type: "youtube" as const, index, language: track.code})),
    languageCode
  );
  return {
    main: picked.primary ? tracks[picked.primary.index] : null,
    translation: picked.secondary ? tracks[picked.secondary.index] : null
  };
};
