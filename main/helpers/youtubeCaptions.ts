export interface YoutubeCaptionTrack {
  code: string;
  name: string;
  isAutoGenerated: boolean;
}

interface CaptionFormat {
  ext?: string;
  name?: string;
}

type CaptionMap = Record<string, CaptionFormat[]>;

// A livestream's chat replay is listed beside its subtitles; it is not a language track.
const LIVE_CHAT = "live_chat";
// Suffix of the speech-recognition original (`en-orig`); yt-dlp accepts the full key as a --sub-langs value.
const ORIGINAL_SUFFIX = "-orig";
const ORIGINAL_NAME_SUFFIX = / \(Original\)$/;
const AUTO_TRANSLATED_ENGLISH = "en";

const displayNames = new Intl.DisplayNames(["en"], {type: "language"});

const languageName = (code: string): string => {
  try {
    return displayNames.of(code) || code;
  } catch {
    // DisplayNames throws a RangeError for tags it cannot parse.
    return code;
  }
};

const firstName = (formats: CaptionFormat[]) => formats.find((format) => format.name)?.name;
const baseLanguage = (code: string) => code.split("-")[0].toLowerCase();
const byName = (a: YoutubeCaptionTrack, b: YoutubeCaptionTrack) => a.name.localeCompare(b.name);
const nonEmptyEntries = (captions?: CaptionMap) =>
  Object.entries(captions ?? {}).filter(([, formats]) => Array.isArray(formats) && formats.length > 0);

/**
 * The caption tracks worth offering for a video, from yt-dlp's `-J` output: every uploader (manual)
 * track, then the speech-recognition original, then an English translation of it as a reference line.
 * The rest of `automatic_captions` is left out: yt-dlp repeats each manual track there as a nameless
 * vtt playlist, and lists YouTube's machine translations of the original (or of a manual track,
 * keyed `<target>-<source>` and named "English from Chinese") under every language.
 */
export function listYoutubeCaptionTracks(info: {
  subtitles?: CaptionMap;
  automatic_captions?: CaptionMap;
}): YoutubeCaptionTrack[] {
  const manualEntries = nonEmptyEntries(info?.subtitles).filter(([code]) => code !== LIVE_CHAT);
  const manualCodes = new Set(manualEntries.map(([code]) => code));
  const manual: YoutubeCaptionTrack[] = manualEntries.map(([code, formats]) => ({
    code,
    name: firstName(formats) || languageName(code),
    isAutoGenerated: false
  }));

  const autoEntries = nonEmptyEntries(info?.automatic_captions).filter(([code]) => !manualCodes.has(code));
  const originals = autoEntries.filter(([code]) => code.endsWith(ORIGINAL_SUFFIX));
  const auto: YoutubeCaptionTrack[] = originals.map(([code, formats]) => ({
    code,
    name: firstName(formats)?.replace(ORIGINAL_NAME_SUFFIX, "") || languageName(code.slice(0, -ORIGINAL_SUFFIX.length)),
    isAutoGenerated: true
  })).sort(byName);

  if (originals.length > 0) {
    // Every other plain key is a machine translation of the original; keep only English, which
    // is the reference line a learner of another language wants, unless the video already has it.
    const hasEnglish = [...manualCodes, ...originals.map(([code]) => code)]
      .some((code) => baseLanguage(code) === AUTO_TRANSLATED_ENGLISH);
    if (!hasEnglish && autoEntries.some(([code]) => code === AUTO_TRANSLATED_ENGLISH)) {
      auto.push({code: AUTO_TRANSLATED_ENGLISH, name: "English (auto-translated)", isAutoGenerated: true});
    }
  } else {
    for (const [code, formats] of autoEntries) {
      const name = firstName(formats);
      if (name?.includes(" from ")) continue;
      auto.push({code, name: name || languageName(code), isAutoGenerated: true});
    }
    auto.sort(byName);
  }

  // The English translation stays after the original it comes from.
  return [...manual.sort(byName), ...auto];
}
