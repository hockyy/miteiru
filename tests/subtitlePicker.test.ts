import assert from "node:assert/strict";
import {describe, it} from "node:test";
import {
  describeEmbeddedTrack,
  describeYoutubeCaption,
  isPictureSubtitleCodec,
  languageNameFromCode,
  mainSubtitleName,
  mainSubtitleNameInSentence,
  PICTURE_SUBTITLE_NOTE,
  pickerFooterText,
  TRANSLATION_NAME
} from "../renderer/utils/subtitleLabels";
import {pickDefaultAudioTrack, pickDefaultSubtitleTracks, type SubtitleCandidate} from "../renderer/utils/mediaUtils";

describe("picture subtitles", () => {
  it("recognises the picture formats and not the text ones", () => {
    for (const codec of ["hdmv_pgs_subtitle", "dvd_subtitle", "dvb_subtitle", "DVD_SUBTITLE", "xsub"]) {
      assert.equal(isPictureSubtitleCodec(codec), true, codec);
    }
    for (const codec of ["subrip", "ass", "ssa", "webvtt", "mov_text", "srt", "", undefined]) {
      assert.equal(isPictureSubtitleCodec(codec), false, String(codec));
    }
  });

  it("lists a picture track as unusable, with no upper-case codec in the label", () => {
    const picture = describeEmbeddedTrack({index: 3, type: "subtitle", codec: "hdmv_pgs_subtitle", language: "jpn"}, 0);
    assert.equal(picture.picture, true);
    assert.equal(PICTURE_SUBTITLE_NOTE, "picture subtitles, can't be used");
    const text = describeEmbeddedTrack({index: 2, type: "subtitle", codec: "subrip", language: "eng", default: true}, 1);
    assert.deepEqual(text, {label: "English (default)", picture: false});
    assert.ok(!/SUBRIP|HDMV|PGS/.test(JSON.stringify([picture, text])));
  });

  it("never preselects a picture track, even when it is the best match", () => {
    const candidates: SubtitleCandidate[] = [
      {type: "embedded", index: 0, language: "jpn", unusable: true},
      {type: "embedded", index: 1, language: "eng"},
      {type: "embedded", index: 2, language: "jpn"}
    ];
    const {primary, secondary} = pickDefaultSubtitleTracks(candidates, "ja");
    assert.equal(primary?.index, 2);
    assert.equal(secondary?.index, 1);
    const onlyPicture = pickDefaultSubtitleTracks([{type: "embedded", index: 0, language: "jpn", unusable: true}], "ja");
    assert.equal(onlyPicture.primary, null);
  });
});

describe("the picker's names and footer", () => {
  it("names the two subtitles by language and 'Translation'", () => {
    assert.equal(mainSubtitleName("Japanese"), "Japanese subtitles");
    assert.equal(mainSubtitleName(""), "Main subtitles");
    assert.equal(mainSubtitleNameInSentence("Japanese"), "Japanese subtitles");
    assert.equal(mainSubtitleNameInSentence("main"), "main subtitles");
    assert.equal(TRANSLATION_NAME, "Translation");
  });

  it("reads like 'Japanese (YouTube, auto) + English', not 'Primary: #2'", () => {
    const auto = {source: "youtube" as const, language: "ja", autoGenerated: true, position: 1};
    const english = {source: "embedded" as const, language: "eng", position: 0};
    assert.equal(pickerFooterText(auto, {source: "youtube", language: "en", position: 4}), "Japanese (YouTube, auto) + English (YouTube)");
    assert.equal(pickerFooterText({source: "embedded", language: "jpn", position: 2}, english), "Japanese + English");
    assert.equal(pickerFooterText(auto, null), "Japanese (YouTube, auto)");
    assert.equal(pickerFooterText(null, english), "English as translation");
    assert.equal(pickerFooterText(null, null), "No subtitles selected");
    assert.ok(!/#\d|Primary|Secondary/.test(pickerFooterText(auto, english)));
  });

  it("falls back to the track's title, then its place, when the language is unknown", () => {
    assert.equal(pickerFooterText({source: "embedded", language: "und", title: "Commentary", position: 0}, null), "Commentary");
    assert.equal(pickerFooterText({source: "embedded", position: 4}, null), "Track 5");
  });

  it("turns language codes into names", () => {
    assert.equal(languageNameFromCode("ja"), "Japanese");
    assert.equal(languageNameFromCode("jpn"), "Japanese");
    assert.equal(languageNameFromCode("ja-orig"), "Japanese");
    assert.equal(languageNameFromCode("zh-Hant"), "Chinese (Traditional)");
    assert.equal(languageNameFromCode("und"), undefined);
    assert.equal(describeYoutubeCaption({language: "ja", name: "Japanese", isAutoGenerated: true}), "Japanese (auto-generated)");
  });
});

describe("pickDefaultAudioTrack", () => {
  it("prefers the learning language's track, then the file's default, then the first", () => {
    const tracks = [{language: "eng", default: true}, {language: "jpn"}];
    assert.equal(pickDefaultAudioTrack(tracks, "ja"), 1);
    assert.equal(pickDefaultAudioTrack(tracks, "vi"), 0);
    assert.equal(pickDefaultAudioTrack([{language: "eng"}, {language: "fra", default: true}], "ja"), 1);
    assert.equal(pickDefaultAudioTrack([{language: "eng"}, {language: "fra"}], "ja"), 0);
    assert.equal(pickDefaultAudioTrack([], "ja"), 0);
  });

  it("matches Chinese and Cantonese tags", () => {
    assert.equal(pickDefaultAudioTrack([{language: "eng", default: true}, {language: "chi"}], "zh-CN"), 1);
    assert.equal(pickDefaultAudioTrack([{language: "zho"}, {language: "yue"}], "yue"), 1);
  });
});
