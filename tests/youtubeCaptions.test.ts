import assert from "node:assert/strict";
import {describe, it} from "node:test";
import {listYoutubeCaptionTracks} from "../main/helpers/youtubeCaptions";

// Trimmed from real `yt-dlp -J` output (2026.08.19): urls and client details dropped, keys, ext and name kept.
const FORMATS = ["json3", "srv1", "srv2", "srv3", "ttml", "srt", "vtt"];
const track = (name: string) => FORMATS.map((ext) => ({ext, name}));
// yt-dlp repeats every manual track under automatic_captions as a nameless HLS playlist.
const hlsDuplicates = (codes: string[]) => Object.fromEntries(codes.map((code) => [code, [{ext: "vtt"}]]));
const tracks = (entries: [string, string][]) => Object.fromEntries(entries.map(([code, name]) => [code, track(name)]));
const summary = (list: ReturnType<typeof listYoutubeCaptionTracks>) =>
  list.map(({code, name, isAutoGenerated}) => `${code}|${name}|${isAutoGenerated}`);

const PEPPA: [string, string][] = [
  ["zh", "Chinese"],
  ["zh-HK", "Chinese (Hong Kong)"],
  ["zh-CN", "Chinese (China)"],
  ["zh-Hans", "Chinese (Simplified)"],
  ["zh-SG", "Chinese (Singapore)"],
  ["zh-Hant", "Chinese (Traditional)"],
  ["zh-TW", "Chinese (Taiwan)"],
  ["en-GB", "English (United Kingdom)"]
];

const MANY_MANUAL: [string, string][] = [
  ["ar", "Arabic"], ["bn", "Bangla"], ["my", "Burmese"], ["zh", "Chinese"], ["zh-CN", "Chinese (China)"],
  ["zh-Hant", "Chinese (Traditional)"], ["en", "English"], ["fil", "Filipino"], ["fr", "French"],
  ["de", "German"], ["hi", "Hindi"], ["id", "Indonesian"], ["it", "Italian"], ["ja", "Japanese"],
  ["km", "Khmer"], ["ko", "Korean"], ["lo", "Lao"], ["pt", "Portuguese"], ["ru", "Russian"],
  ["es", "Spanish"], ["th", "Thai"], ["vi", "Vietnamese"]
];

// A video with only YouTube speech recognition: the original, then a machine translation per language.
const asrOnly = (original: [string, string]) => ({
  subtitles: {},
  automatic_captions: tracks([
    original,
    ["ab", "Abkhazian"],
    ["en", "English"],
    ["ja", "Japanese"],
    ["zh-Hans", "Chinese (Simplified)"]
  ])
});

describe("listYoutubeCaptionTracks", () => {
  it("lists every manual track of a video and ignores the nameless HLS duplicates", () => {
    const list = listYoutubeCaptionTracks({
      subtitles: tracks(PEPPA),
      automatic_captions: hlsDuplicates(PEPPA.map(([code]) => code))
    });

    assert.equal(list.length, 8);
    assert.ok(list.every((entry) => !entry.isAutoGenerated));
    assert.deepEqual(list.map((entry) => entry.code), ["zh", "zh-CN", "zh-HK", "zh-Hans", "zh-SG", "zh-TW", "zh-Hant", "en-GB"]);
    assert.deepEqual(list[0], {code: "zh", name: "Chinese", isAutoGenerated: false});
  });

  it("keeps three-letter codes such as fil", () => {
    const list = listYoutubeCaptionTracks({
      subtitles: tracks(MANY_MANUAL),
      automatic_captions: hlsDuplicates(MANY_MANUAL.map(([code]) => code))
    });

    assert.equal(list.length, 22);
    assert.ok(list.every((entry) => !entry.isAutoGenerated));
    assert.deepEqual(list.find((entry) => entry.code === "fil"), {code: "fil", name: "Filipino", isAutoGenerated: false});
  });

  it("returns nothing for a livestream that only has live chat", () => {
    assert.deepEqual(listYoutubeCaptionTracks({subtitles: {live_chat: [{ext: "json"}]}, automatic_captions: {}}), []);
  });

  it("skips live chat but keeps the real tracks beside it", () => {
    const list = listYoutubeCaptionTracks({subtitles: {...tracks([["ja", "Japanese"]]), live_chat: [{ext: "json"}]}});
    assert.deepEqual(summary(list), ["ja|Japanese|false"]);
  });

  it("returns nothing when there are no captions at all", () => {
    assert.deepEqual(listYoutubeCaptionTracks({}), []);
    assert.deepEqual(listYoutubeCaptionTracks({subtitles: {}, automatic_captions: {}}), []);
  });

  it("offers the English original of a speech-recognition-only video without a translation of it", () => {
    const list = listYoutubeCaptionTracks(asrOnly(["en-orig", "English (Original)"]));
    assert.deepEqual(list, [{code: "en-orig", name: "English", isAutoGenerated: true}]);
  });

  it("adds one English translation beside a non-English speech-recognition original", () => {
    const list = listYoutubeCaptionTracks(asrOnly(["zh-orig", "Chinese (Original)"]));
    assert.deepEqual(summary(list), ["zh-orig|Chinese|true", "en|English (auto-translated)|true"]);
  });

  it("adds no English translation when a manual English track exists", () => {
    const list = listYoutubeCaptionTracks({
      subtitles: tracks([["en-US", "English (United States)"]]),
      automatic_captions: {
        ...hlsDuplicates(["en-US"]),
        ...asrOnly(["zh-orig", "Chinese (Original)"]).automatic_captions
      }
    });
    assert.deepEqual(summary(list), ["en-US|English (United States)|false", "zh-orig|Chinese|true"]);
  });

  it("drops translations of manual tracks keyed <target>-<source>", () => {
    const list = listYoutubeCaptionTracks({
      subtitles: tracks([["zh", "Chinese"]]),
      automatic_captions: {
        ...hlsDuplicates(["zh"]),
        "en-zh": [{ext: "vtt", name: "English from Chinese"}],
        "ab-zh-HK": [{ext: "vtt", name: "Abkhazian from Chinese (Hong Kong)"}]
      }
    });
    assert.deepEqual(summary(list), ["zh|Chinese|false"]);
  });

  it("falls back to named automatic tracks when there is no original", () => {
    const list = listYoutubeCaptionTracks({
      subtitles: {},
      automatic_captions: {
        ko: [{ext: "vtt", name: "Korean"}],
        "en-ko": [{ext: "vtt", name: "English from Korean"}],
        fr: [{ext: "vtt"}]
      }
    });
    assert.deepEqual(summary(list), ["fr|French|true", "ko|Korean|true"]);
  });

  it("names a track without a name from its language code, and survives a code it cannot name", () => {
    const list = listYoutubeCaptionTracks({
      subtitles: {de: [{ext: "vtt"}], "not a language": [{ext: "vtt"}], nl: []}
    });
    assert.deepEqual(summary(list), ["de|German|false", "not a language|not a language|false"]);
  });

  it("puts manual tracks first, then the original, then its English translation", () => {
    const list = listYoutubeCaptionTracks({
      subtitles: tracks([["ja", "Japanese"], ["de", "German"]]),
      automatic_captions: tracks([["fr-orig", "French (Original)"], ["en", "English"]])
    });
    assert.deepEqual(summary(list), [
      "de|German|false",
      "ja|Japanese|false",
      "fr-orig|French|true",
      "en|English (auto-translated)|true"
    ]);
  });
});
