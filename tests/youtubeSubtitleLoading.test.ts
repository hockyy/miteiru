import assert from "node:assert/strict";
import {afterEach, test} from "node:test";
import React from "react";
import {deferred, flushPromises, HookHost, loadHooks as load} from "./helpers/reactHookHost";
const globals = globalThis as Record<string, any>;
const savedWindow = globals.window;
afterEach(() => {
  if (savedWindow === undefined) delete globals.window;
  else globals.window = savedWindow;
});

const FIRST = "https://www.youtube.com/watch?v=abcdefghijk";
const SECOND = "https://www.youtube.com/watch?v=lmnopqrstuv";
const JAPANESE = {languages: [{code: "ja-orig", name: "Japanese", isAutoGenerated: true}]};
const ENGLISH = {languages: [{code: "en", name: "English"}]};

test("a slow listing from the previous video cannot replace the current captions", async () => {
  const host = new HookHost();
  const {useYoutubeSubtitles}: typeof import("../renderer/hooks/useYoutubeSubtitles") = load("renderer/hooks/useYoutubeSubtitles.tsx", host);
  const first = deferred();
  const second = deferred();
  globals.window = {backend: {invoke: (_channel: string, id: string) => id === "abcdefghijk" ? first.promise : second.promise}};
  const read = () => host.render(useYoutubeSubtitles);
  try {
    const firstLoad = read().fetchAvailableSubtitles(FIRST);
    const secondLoad = read().fetchAvailableSubtitles(SECOND);
    assert.equal(read().isLoading, true);
    second.resolve(ENGLISH);
    await secondLoad;
    assert.equal(read().subtitles[0].language, "en");
    first.resolve(JAPANESE);
    await firstLoad;
    assert.equal(read().subtitles[0].language, "en");
    assert.equal(read().isLoading, false);
  } finally {
    read().clearSubtitles();
    host.dispose();
  }
});

test("a stalled caption listing stops loading after 30 seconds and can be retried", async (t) => {
  t.mock.timers.enable({apis: ["setTimeout"]});
  const host = new HookHost();
  const {useYoutubeSubtitles}: typeof import("../renderer/hooks/useYoutubeSubtitles") = load("renderer/hooks/useYoutubeSubtitles.tsx", host);
  const stuck = deferred();
  let calls = 0;
  globals.window = {backend: {invoke: () => ++calls === 1 ? stuck.promise : Promise.resolve(JAPANESE)}};
  const read = () => host.render(useYoutubeSubtitles);
  try {
    const listing = read().fetchAvailableSubtitles(FIRST);
    t.mock.timers.tick(29_999);
    await flushPromises();
    assert.equal(read().isLoading, true);
    t.mock.timers.tick(1);
    await listing;
    assert.equal(read().isLoading, false);
    assert.match(read().error, /taking too long/i);
    await read().fetchAvailableSubtitles(FIRST);
    assert.equal(read().hasLoaded, true);
    assert.equal(read().error, null);
    assert.equal(read().subtitles[0].language, "ja-orig");
    stuck.resolve(ENGLISH);
    await flushPromises();
    assert.equal(read().subtitles[0].language, "ja-orig");
  } finally {
    read().clearSubtitles();
    host.dispose();
  }
});

test("clearing a listing discards late replies and cancels its loading deadline", async (t) => {
  t.mock.timers.enable({apis: ["setTimeout"]});
  const host = new HookHost();
  const {useYoutubeSubtitles}: typeof import("../renderer/hooks/useYoutubeSubtitles") = load("renderer/hooks/useYoutubeSubtitles.tsx", host);
  const reply = deferred();
  globals.window = {backend: {invoke: () => reply.promise}};
  const read = () => host.render(useYoutubeSubtitles);
  const listing = read().fetchAvailableSubtitles(FIRST);
  read().clearSubtitles();
  t.mock.timers.tick(30_000);
  reply.resolve(JAPANESE);
  await listing;
  assert.equal(read().isLoading, false);
  assert.equal(read().hasLoaded, false);
  assert.deepEqual(read().subtitles, []);
  assert.equal(read().error, null);
  host.dispose();
});

test("the closed subtitle picker prefetches once and retains captions across close and reopen", async () => {
  const host = new HookHost();
  const Modal = load("renderer/components/Utils/MediaTrackSelectionModal.tsx", host).default;
  const reply = deferred();
  const calls: any[][] = [];
  globals.window = {backend: {invoke: (...args: any[]) => { calls.push(args); return reply.promise; }}};
  const props = {
    isOpen: false, onClose() {}, onConfirm() {}, fileName: "Long video",
    subtitleTracks: [], currentAppLanguage: "Japanese", appLanguageCode: "ja", videoUrl: FIRST
  };
  const read = () => host.render(() => Modal(props));
  try {
    assert.equal(read(), null);
    assert.deepEqual(calls, [["getYoutubeSubtitleLanguages", "abcdefghijk"]]);
    reply.resolve(JAPANESE);
    await flushPromises();
    props.isOpen = true;
    const opened = read();
    assert.ok(opened);
    const buttons = React.Children.toArray(opened.props.footer.props.children[1].props.children) as any[];
    assert.equal(buttons[0].props.children, "Keep watching");
    assert.equal(buttons[1].props.disabled, false);
    props.isOpen = false;
    assert.equal(read(), null);
    props.isOpen = true;
    const reopened = read();
    const reopenedButtons = React.Children.toArray(reopened.props.footer.props.children[1].props.children) as any[];
    assert.equal(reopenedButtons[1].props.disabled, false);
    assert.equal(calls.length, 1);
  } finally {
    host.dispose();
  }
});

