import type {MediaTrack} from "../types/media";
import {normalizeSubtitleLanguage} from "./mediaUtils";

/**
 * The words the learner reads for the two subtitles: the one in the language being learned is named
 * after that language ("Japanese subtitles"), the other one is the "Translation".
 */
export const TRANSLATION_NAME = "Translation";

/** "Japanese subtitles"; before a language is known, "Main subtitles". */
export const mainSubtitleName = (languageName?: string): string => (
  languageName && languageName !== "main" ? `${languageName} subtitles` : "Main subtitles"
);

/** The same inside a sentence: "the Japanese subtitles", "the main subtitles". */
export const mainSubtitleNameInSentence = (languageName?: string): string => (
  languageName && languageName !== "main" ? `${languageName} subtitles` : "main subtitles"
);

/** The one name of the all-caps option, in both subtitle dialogs. */
export const ALL_CAPS_OPTION_LABEL = "Fix all-caps subtitles";
export const ALL_CAPS_OPTION_HINT = "Turns LINES IN CAPITALS into normal sentences.";

// Subtitle formats that are pictures (Blu-ray and DVD rips, broadcast): there is no text to read.
const PICTURE_SUBTITLE_CODECS = new Set([
  "hdmv_pgs_subtitle", "pgssub", "dvd_subtitle", "dvdsub", "dvb_subtitle", "dvbsub", "xsub", "vobsub"
]);

/** Whether a subtitle track is made of pictures, so Miteiru can't use it. */
export const isPictureSubtitleCodec = (codec?: string): boolean => (
  PICTURE_SUBTITLE_CODECS.has((codec ?? "").toLowerCase())
);

export const PICTURE_SUBTITLE_NOTE = "picture subtitles, can't be used";

const NAMES: Record<string, string> = {
  ja: "Japanese", en: "English", zh: "Chinese", "zh-hans": "Chinese (Simplified)", "zh-cn": "Chinese (Simplified)",
  "zh-sg": "Chinese (Simplified)", "zh-hant": "Chinese (Traditional)", "zh-tw": "Chinese (Traditional)",
  "zh-hk": "Chinese (Hong Kong)", yue: "Cantonese", vi: "Vietnamese", ko: "Korean", es: "Spanish",
  fr: "French", de: "German", it: "Italian", pt: "Portuguese", ru: "Russian", id: "Indonesian",
  th: "Thai", ar: "Arabic", hi: "Hindi", tr: "Turkish", nl: "Dutch", pl: "Polish"
};

/** "Japanese" for `ja`, `jpn` or `ja-orig`; undefined when the code is not known. */
export const languageNameFromCode = (code?: string): string | undefined => {
  if (!code || ["und", "mis", "mul", "zxx"].includes(code.toLowerCase())) return undefined;
  const normalized = normalizeSubtitleLanguage(code);
  if (NAMES[normalized]) return NAMES[normalized];
  try {
    const name = new Intl.DisplayNames(["en"], {type: "language"}).of(normalized);
    return name && name.toLowerCase() !== normalized ? name : undefined;
  } catch {
    return undefined;
  }
};

/** What a subtitle inside the video is called in the picker: "Japanese · Full subs (default)". */
export const describeEmbeddedTrack = (track: MediaTrack, position: number): {
  label: string;
  picture: boolean;
} => {
  const language = languageNameFromCode(track.language);
  const title = track.title?.trim();
  const parts = [language, title && title !== language ? title : undefined].filter(Boolean);
  const label = `${parts.length > 0 ? parts.join(" · ") : `Track ${position + 1}`}${track.default ? " (default)" : ""}`;
  return {label, picture: isPictureSubtitleCodec(track.codec)};
};

/** What a YouTube caption is called: "Japanese (auto-generated)". */
export const describeYoutubeCaption = (caption: { language: string; name: string; isAutoGenerated?: boolean }): string => {
  const name = languageNameFromCode(caption.language) ?? caption.name ?? caption.language;
  return `${name}${caption.isAutoGenerated ? " (auto-generated)" : ""}`;
};

export type PickedSubtitle = {
  source: "embedded" | "youtube";
  language?: string;
  autoGenerated?: boolean;
  /** A track's title, for when its language is unknown. */
  title?: string;
  position: number;
};

const pickedName = (pick: PickedSubtitle): string => {
  const language = languageNameFromCode(pick.language);
  const base = language ?? pick.title?.trim() ?? `Track ${pick.position + 1}`;
  if (pick.source === "youtube") return `${base} (${pick.autoGenerated ? "YouTube, auto" : "YouTube"})`;
  return base;
};

/**
 * The summary in the picker's footer: "Japanese (YouTube, auto) + English". A translation chosen
 * without a main subtitle says so.
 */
export const pickerFooterText = (primary: PickedSubtitle | null, secondary: PickedSubtitle | null): string => {
  if (!primary && !secondary) return "No subtitles selected";
  if (primary && secondary) return `${pickedName(primary)} + ${pickedName(secondary)}`;
  if (primary) return pickedName(primary);
  return `${pickedName(secondary as PickedSubtitle)} as translation`;
};
